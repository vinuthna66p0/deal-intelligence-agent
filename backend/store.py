"""
Lightweight JSON-file store for deal + note *metadata* only (names, dates,
tags for the UI timeline). The actual "intelligence" -- what was said, what
objections came up, what worked -- lives in Hindsight, not here. This store
exists purely so the frontend has something fast to render a timeline from
without round-tripping to Hindsight for every list view.

It also holds a structured *experience ledger* (one row per recorded outcome)
and a log of past recommendations. Every ledger row is retained into Hindsight
at the same time it is written here, so the ledger is a verifiable mirror of
what Hindsight was taught. Evidence counts shown in the UI are computed from
this ledger, never generated by an LLM.
"""
import json
import os
import threading
import uuid
from datetime import datetime, timezone
from typing import Optional

DATA_PATH = os.path.join(os.path.dirname(__file__), "data.json")
_lock = threading.Lock()


def _empty_db():
    return {"deals": {}, "notes": {}, "experiences": [], "recommendations": []}


def _load():
    if not os.path.exists(DATA_PATH):
        return _empty_db()
    with open(DATA_PATH, "r") as f:
        try:
            db = json.load(f)
        except json.JSONDecodeError:
            return _empty_db()
    # Older data.json files predate the ledger; upgrade them in memory.
    db.setdefault("deals", {})
    db.setdefault("notes", {})
    db.setdefault("experiences", [])
    db.setdefault("recommendations", [])
    return db


def _save(db):
    with open(DATA_PATH, "w") as f:
        json.dump(db, f, indent=2, default=str)


def now_iso():
    return datetime.now(timezone.utc).isoformat()


def create_deal(company: str, contact_name: str, contact_title: str,
                 deal_value: Optional[float] = None, stage: str = "Discovery") -> dict:
    with _lock:
        db = _load()
        deal_id = company.lower().replace(" ", "-").replace(",", "") + "-" + uuid.uuid4().hex[:5]
        deal = {
            "id": deal_id,
            "company": company,
            "contact_name": contact_name,
            "contact_title": contact_title,
            "deal_value": deal_value,
            "stage": stage,
            "created_at": now_iso(),
        }
        db["deals"][deal_id] = deal
        db["notes"][deal_id] = []
        _save(db)
        return deal


def list_deals() -> list:
    db = _load()
    return sorted(db["deals"].values(), key=lambda d: d["created_at"], reverse=True)


def get_deal(deal_id: str) -> Optional[dict]:
    db = _load()
    return db["deals"].get(deal_id)


def find_deal_by_company(company: str) -> Optional[dict]:
    """Look a deal up by company name. Used by seed.py so re-running it reuses
    the existing demo deal instead of creating a second copy of it."""
    target = " ".join((company or "").lower().split())
    for deal in _load()["deals"].values():
        if " ".join((deal.get("company") or "").lower().split()) == target:
            return deal
    return None


def update_deal_stage(deal_id: str, stage: str):
    with _lock:
        db = _load()
        if deal_id in db["deals"]:
            db["deals"][deal_id]["stage"] = stage
            _save(db)


def add_note(deal_id: str, note_type: str, raw_notes: str,
             objection_type: Optional[str] = None, outcome: Optional[str] = None,
             tactic_used: Optional[str] = None, call_date: Optional[str] = None,
             stakeholder: Optional[str] = None, competitor: Optional[str] = None) -> dict:
    with _lock:
        db = _load()
        note = {
            "id": uuid.uuid4().hex[:8],
            "deal_id": deal_id,
            "note_type": note_type,
            "raw_notes": raw_notes,
            "objection_type": objection_type,
            "outcome": outcome,
            "tactic_used": tactic_used,
            "stakeholder": stakeholder,
            "competitor": competitor,
            "timestamp": call_date or now_iso(),
        }
        db["notes"].setdefault(deal_id, []).append(note)
        _save(db)
        return note


def list_notes(deal_id: str) -> list:
    db = _load()
    return sorted(db["notes"].get(deal_id, []), key=lambda n: n["timestamp"])


def note_exists(deal_id: str, raw_notes: str) -> bool:
    """True if a note with exactly this text is already on the deal. Seeded
    notes have fixed text, so this is what makes re-running seed.py a no-op
    (their timestamps are relative to today and would otherwise drift)."""
    return any(n.get("raw_notes") == raw_notes for n in _load()["notes"].get(deal_id, []))


# ---------- Experience ledger (structured mirror of outcome memories) ----------

def add_experience(exp: dict) -> dict:
    """Append one ledger row. If a row with the same id already exists it is
    returned untouched -- ids are deterministic for seeded demo data, so
    re-running seed.py never duplicates an experience."""
    with _lock:
        db = _load()
        row = dict(exp)
        row.setdefault("id", uuid.uuid4().hex[:8])
        for existing in db["experiences"]:
            if existing.get("id") == row["id"]:
                return existing
        row.setdefault("created_at", now_iso())
        db["experiences"].append(row)
        _save(db)
        return row


def get_experience(exp_id: str) -> Optional[dict]:
    for row in _load()["experiences"]:
        if row.get("id") == exp_id:
            return row
    return None


def list_experiences(objection_type: Optional[str] = None,
                     deal_id: Optional[str] = None) -> list:
    rows = _load()["experiences"]
    if objection_type:
        rows = [r for r in rows if r.get("objection_type") == objection_type]
    if deal_id:
        rows = [r for r in rows if r.get("deal_id") == deal_id]
    return sorted(rows, key=lambda r: (r.get("date") or "", r.get("created_at") or ""))


# ---------- Recommendation log (lets the UI show "before vs after") ----------

def list_recommendations(objection_type: Optional[str] = None) -> list:
    rows = _load()["recommendations"]
    if objection_type:
        rows = [r for r in rows if r.get("objection_type") == objection_type]
    return sorted(rows, key=lambda r: r.get("created_at") or "")


def save_recommendation(rec: dict) -> dict:
    """Append a recommendation snapshot. If the newest snapshot for this
    objection type describes exactly the same evidence state, just refresh its
    last_seen instead of adding a duplicate row.

    Two different counters are kept, and the difference matters for the
    learning-curve view:

      * `version`          -- how many *distinct* evidence states this
                              objection type has been through (a new row).
      * `times_asked`      -- how many times this same state was served.
      * `first_interaction`/`last_interaction` -- the running count of every
                              recommendation ever asked for this objection
                              type, so "interaction 1 / 5 / 12" in the UI is a
                              real number read back out of this log, never a
                              made-up milestone.
    """
    with _lock:
        db = _load()
        same_type = [r for r in db["recommendations"]
                     if r.get("objection_type") == rec["objection_type"]]
        interaction = sum(r.get("times_asked", 1) for r in same_type) + 1
        if same_type and same_type[-1].get("signature") == rec["signature"]:
            latest = same_type[-1]
            latest["last_seen"] = now_iso()
            latest["times_asked"] = latest.get("times_asked", 1) + 1
            latest.setdefault("first_interaction", latest.get("version", 1))
            latest["last_interaction"] = interaction
            _save(db)
            return latest
        row = dict(rec)
        row["id"] = uuid.uuid4().hex[:8]
        row["created_at"] = row["last_seen"] = now_iso()
        row["version"] = len(same_type) + 1
        row["times_asked"] = 1
        row["first_interaction"] = row["last_interaction"] = interaction
        db["recommendations"].append(row)
        _save(db)
        return row


def reset_all():
    with _lock:
        _save(_empty_db())
